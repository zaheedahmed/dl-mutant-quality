#!/usr/bin/env python3
"""
Quality-Driven Selective Mutation for Deep Learning

This script computes, per bug:
- Extrinsic Quality (EQ): generalized Jaccard similarity (fuzzy IoU) between each mutant and the fault.
- Intrinsic Quality (IQ): probabilistic resistance + discriminating-kill behavior.

Inputs:
- results/killing_probability/killing_probability_<bug>_<mutant_type>.pkl
  (generated by killing_probability.py)

Outputs (per bug):
- results/quality/quality_<bug>_<mutant_type>.pkl
- results/quality/quality_<bug>_<mutant_type>.csv
"""

import numpy as np
import pandas as pd
import os
import pickle

# =============================================================================
# CONFIGURATION SECTION - ALIGNED WITH EXISTING PIPELINE
# =============================================================================

# Import bug configuration from execution matrix script (if available)
try:
    from execution_matrix import BUG_CONFIG
    BUG_LIST = list(BUG_CONFIG.keys())
except ImportError:
    BUG_LIST = ['cleanml001', 'cleanml002']

RESULTS_ROOT = 'results/'

# Mutant types to process - should match execution_matrix.py & killing_probability.py
MUTANT_TYPES = [
     'pre-training',
    # 'post-training/scenario1_mutants',
    # 'post-training/scenario2_mutants'
]

# Optional reliability knobs (kept for future use; not used for selection decisions)
MIN_TEST_INPUTS = 5
CONFIDENCE_THRESHOLD = 0.50

# =============================================================================


def load_killing_probabilities(file_path):
    """Load the killing probability matrix and metadata from a pickle file."""
    with open(file_path, 'rb') as f:
        data = pickle.load(f)

    return (
        data['killing_prob_matrix'],
        data['mutant_types'],
        data['confidence_intervals'],
        data.get('mutant_type_info', {}),
        data.get('bug_id'),
        data.get('mutant_type')
    )


def parse_mm_label(bug_id: str, mm_label: str):
    """
    Parse an MM column label into (operator, config_str).

    Example:
      MM_defect4ml100_add_noise_mutated0_MP_100

    - operator: substring between '<bug_id>_' and '_mutated...'
    - config_str: everything after '_MP_'
    """
    label = mm_label
    if label.startswith("MM_"):
        label = label[3:]  # strip "MM_"

    # Remove bug prefix if present
    if label.startswith(bug_id + "_"):
        remainder = label[len(bug_id) + 1:]
    else:
        remainder = label

    # Operator: before the "_mutated" separator if present
    if "_mutated" in remainder:
        op_part, _ = remainder.split("_mutated", 1)
    else:
        op_part = remainder
    operator = op_part

    # Configuration string: everything after "_MP_" if present
    config_str = ""
    if "_MP_" in remainder:
        config_str = remainder.split("_MP_", 1)[1]

    return operator, config_str


def calculate_eq_per_mutant(killing_prob_matrix, mutant_types, confidence_intervals,
                            min_test_inputs=5, confidence_threshold=0.50):
    """
    Compute EQ per mutant as generalized Jaccard similarity (fuzzy IoU) against the fault.

    Returns:
      eq_values: array of length #MM
      mm_indices: indices of MM columns
      fm_indices: indices of FM columns
      reliable_eq: boolean array of length #MM (optional reliability)
    """
    mm_indices = [i for i, mt in enumerate(mutant_types) if mt.startswith('MM_')]
    fm_indices = [i for i, mt in enumerate(mutant_types) if mt.startswith('FM_')]

    if len(fm_indices) == 0:
        raise ValueError("No FM_ column found in killing probabilities. Expected exactly one FM_ per bug.")

    fm_idx = fm_indices[0]
    pf = killing_prob_matrix[:, fm_idx]
    pf_ci = confidence_intervals[:, fm_idx, :]

    eq_values = np.zeros(len(mm_indices), dtype=float)
    reliable_eq = np.zeros(len(mm_indices), dtype=bool)

    for i, mm_idx in enumerate(mm_indices):
        pm = killing_prob_matrix[:, mm_idx]
        pm_ci = confidence_intervals[:, mm_idx, :]

        sum_min = np.sum(np.minimum(pm, pf))
        sum_max = np.sum(np.maximum(pm, pf))
        eq_values[i] = (sum_min / sum_max) if sum_max > 0 else 0.0

        # Optional reliability logic (retained for potential later use)
        definitive_inputs = []
        for k in range(len(pm)):
            mm_lb, mm_ub = pm_ci[k]
            fm_lb, fm_ub = pf_ci[k]
            if mm_ub < fm_lb or mm_lb > fm_ub:
                definitive_inputs.append(k)

        if len(definitive_inputs) >= min_test_inputs:
            avg_ci_width = float(np.mean([ub - lb for lb, ub in pm_ci]))
            if avg_ci_width <= confidence_threshold:
                reliable_eq[i] = True

    return eq_values, mm_indices, fm_indices, reliable_eq


def calculate_iq_per_mutant(killing_prob_matrix, mutant_types):
    """
    Compute IQ per mutant (per bug).

    Definitions:
      - M = all MM mutants for this bug
      - C_t = (1/|M|) * sum_{m' in M} p_{m'}(t)
      - S_m = (1/|T|) * sum_t p_m(t)

      IQ_m = 0 if S_m == 0
             else (1 - S_m) * (1 - (sum_t p_m(t)*C_t / sum_t p_m(t)))
    """
    mm_indices = [i for i, mt in enumerate(mutant_types) if mt.startswith('MM_')]
    if len(mm_indices) == 0:
        return np.array([]), np.array([]), np.array([])

    P_mm = killing_prob_matrix[:, mm_indices]  # |T| x |M|
    C_t = np.mean(P_mm, axis=1)                # |T|

    iq_values = np.zeros(len(mm_indices), dtype=float)
    S_m_values = np.zeros(len(mm_indices), dtype=float)
    wcov_values = np.zeros(len(mm_indices), dtype=float)  # weighted average of C_t over killing mass

    for i, mm_idx in enumerate(mm_indices):
        pm = killing_prob_matrix[:, mm_idx]
        S_m = float(np.mean(pm))
        S_m_values[i] = S_m

        mass = float(np.sum(pm))
        if S_m == 0.0 or mass == 0.0:
            iq = 0.0
            wcov = 0.0
        else:
            wcov = float(np.sum(pm * C_t) / mass)
            iq = (1.0 - S_m) * (1.0 - wcov)

        iq_values[i] = float(np.clip(iq, 0.0, 1.0))
        wcov_values[i] = float(np.clip(wcov, 0.0, 1.0))

    return iq_values, S_m_values, wcov_values


def process_single_bug_mutant_type(bug_id, mutant_type, results_root):
    """Compute IQ and EQ for a single bug + mutant_type."""
    print(f"\n=== Processing Bug: {bug_id}, Mutant Type: {mutant_type} ===")

    mutant_suffix = mutant_type.replace('/', '_').replace('-', '_')

    killing_prob_file = os.path.join(
        results_root,
        "killing_probability",
        f"killing_probability_{bug_id}_{mutant_suffix}.pkl"
    )

    if not os.path.exists(killing_prob_file):
        print(f"Warning: Killing probability file not found: {killing_prob_file}")
        return None

    (killing_prob_matrix, mutant_types, confidence_intervals,
     mutant_type_info, loaded_bug_id, loaded_mutant_type) = load_killing_probabilities(killing_prob_file)

    print(f"Loaded killing probability matrix with shape {killing_prob_matrix.shape}")

    if loaded_bug_id is not None and loaded_bug_id != bug_id:
        print(f"Warning: Bug ID mismatch. Expected {bug_id}, got {loaded_bug_id}")
    if loaded_mutant_type is not None and loaded_mutant_type != mutant_type:
        print(f"Warning: Mutant type mismatch. Expected {mutant_type}, got {loaded_mutant_type}")

    # EQ per mutant (IoU vs the fault)
    print("Calculating EQ per mutant...")
    eq_values, mm_indices, fm_indices, reliable_eq = calculate_eq_per_mutant(
        killing_prob_matrix, mutant_types, confidence_intervals,
        MIN_TEST_INPUTS, CONFIDENCE_THRESHOLD
    )

    # IQ per mutant
    print("Calculating IQ per mutant...")
    iq_values, S_m_values, wcov_values = calculate_iq_per_mutant(killing_prob_matrix, mutant_types)

    if len(iq_values) != len(mm_indices):
        raise RuntimeError("Mismatch: IQ computed for a different number of mutants than EQ.")

    return {
        "bug_id": bug_id,
        "mutant_type": mutant_type,
        "mutant_suffix": mutant_suffix,
        "mutant_types": mutant_types,
        "mm_indices": mm_indices,
        "fm_indices": fm_indices,
        "iq_values": iq_values,
        "eq_values": eq_values,
        "reliable_eq": reliable_eq,
        "S_m_values": S_m_values,
        "wcov_values": wcov_values
    }


def save_bug_results(result_dict, results_root):
    """Save per-bug quality outputs as both PKL and CSV."""
    bug_id = result_dict["bug_id"]
    mutant_suffix = result_dict["mutant_suffix"]

    output_dir = os.path.join(results_root, "quality")
    os.makedirs(output_dir, exist_ok=True)

    pkl_path = os.path.join(output_dir, f"quality_{bug_id}_{mutant_suffix}.pkl")
    csv_path = os.path.join(output_dir, f"quality_{bug_id}_{mutant_suffix}.csv")

    mm_names = [result_dict["mutant_types"][i] for i in result_dict["mm_indices"]]

    rows = []
    for idx, mm_label in enumerate(mm_names):
        operator, config_str = parse_mm_label(bug_id, mm_label)
        rows.append({
            "bug_id": bug_id,
            "mutant_type": mm_label,
            "operator": operator,
            "config_str": config_str,
            "IQ": float(result_dict["iq_values"][idx]),
            "EQ": float(result_dict["eq_values"][idx]),
            "EQ_reliable": bool(result_dict["reliable_eq"][idx]),
            "S_m": float(result_dict["S_m_values"][idx]),
            "weighted_C": float(result_dict["wcov_values"][idx]),
        })

    df = pd.DataFrame(rows)

    with open(pkl_path, "wb") as f:
        pickle.dump(result_dict, f)

    df.to_csv(csv_path, index=False)

    print("Saved quality results:")
    print(f"  PKL: {pkl_path}")
    print(f"  CSV: {csv_path}")

    return pkl_path, csv_path


def main():
    print("Configuration:")
    print(f"  Bug list: {BUG_LIST}")
    print(f"  Results root: {RESULTS_ROOT}")
    print(f"  Mutant types: {MUTANT_TYPES}")

    print("\nProcessing quality (IQ + EQ) for all bugs and mutant types...")

    processed_count = 0
    for bug_id in BUG_LIST:
        for mutant_type in MUTANT_TYPES:
            result = process_single_bug_mutant_type(bug_id, mutant_type, RESULTS_ROOT)
            if result is None:
                continue

            save_bug_results(result, RESULTS_ROOT)

            # Quick summary
            iq = result["iq_values"]
            eq = result["eq_values"]
            print(f"Bug {bug_id} ({mutant_type}) - Mutants: {len(iq)}")
            if len(iq) > 0:
                print(f"  IQ: mean={np.mean(iq):.4f}, median={np.median(iq):.4f}, max={np.max(iq):.4f}")
                print(f"  EQ: mean={np.mean(eq):.4f}, median={np.median(eq):.4f}, max={np.max(eq):.4f}")

            processed_count += 1

    print("\n=== PROCESSING COMPLETE ===")
    print(f"Successfully processed {processed_count} bug-mutant type combinations.")
    print(f"Quality results saved in: {os.path.join(RESULTS_ROOT, 'quality')}")


if __name__ == "__main__":
    main()